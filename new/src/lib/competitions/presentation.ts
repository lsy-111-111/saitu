export function competitionReadingText(text: string): string {
  if (Object.hasOwn(readingCopy, text)) return readingCopy[text];
  // These catalog templates contain a trial/checklist, not a benefit or a fact.
  if (/^(?:体验时可以这样检查学习：|可自查：|先用小任务检验兴趣和基础：)/u.test(text)) return "";
  const stage = text.match(/^(入门|完赛|竞争奖项)：([\s\S]+)$/u);
  if (stage) {
    const body = competitionReadingText(stage[2]);
    return body ? `${stage[1]}：${body}` : "";
  }
  const taskRelevance = text.match(/^该路径实际任务为：([\s\S]+)相关性须与学生目标相对照。$/u);
  if (taskRelevance) return `该路径实际任务为：${competitionReadingText(taskRelevance[1])}相关性须与学生目标相对照。`;
  // Remove the editorial preparation clause, retaining subsequent cost and
  // eligibility conditions verbatim. "准备40分钟" in official rules is retained.
  return (text.match(/[^。；]+[。；]?/gu) ?? []).filter(part =>
    !/^(?:编辑建议|备赛(?:重点|建议|时|要)|准备时|建议(?:优先|提前)|先做安全低成本小样)/u.test(part.trim()),
  ).join("")
    .replace(/你可以围绕「[^」]+」判断是否喜欢这项工作。/gu, "")
    .replace("备赛可以沉淀", "参赛可积累")
    .replace("并练习把专业判断转化为清晰证据链", "并提升专业判断与证据表达能力")
    .replace("，低预算用户先用公开题学习", "")
    .replace("已有电脑先离线整理，不制作教具、不印刷、不试教，", "")
    .replace("优先现有表格工具，AI不可用时保留手工模型并核正式任务要求，费用另核。", "正式任务的工具要求与费用需另行核对。")
    .trim();
}

export function competitionReadingList(items: readonly string[]): string[] {
  return items.map(competitionReadingText).filter(Boolean);
}

export function competitionReadingClaim<T extends { text: string; conditions: string[] }>(claim: T): T | null {
  const text = competitionReadingText(claim.text);
  return text ? { ...claim, text, conditions: competitionReadingList(claim.conditions) } : null;
}
